"""Medical Practitioner LLM-as-a-Judge Evaluation Framework for CareRoute.

Implements rigorous, 100% LLM-driven post-discharge care plan evaluation based on real
medical practitioner standards:
- AHRQ IDEAL Discharge Planning Framework
- AHRQ Project RED (Re-Engineered Discharge) Toolkit
- AAMC Core Entrustable Professional Activities (EPA 4 & EPA 8)
- ACGME/ABIM Transition of Care Milestone Competencies
- Calgary-Cambridge Medical Communication Guide (6th-grade reading level)

Zero hardcoded fallbacks or deterministic mock scoring. All evaluations execute
live against Google Gemini models.
"""

from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field
from careroute.config import settings
from careroute.core.models import DrugInteractionResult, PersonalizedCarePlan
from careroute.observability.logger import logger
from careroute.observability.tracing import tracer


class JudgeEvaluationReport(BaseModel):
    """Detailed evaluation report generated by the clinical LLM judge."""
    patient_id: str
    overall_score: float = Field(..., ge=1.0, le=5.0, description="Composite score (1.0 - 5.0)")
    passed: bool = Field(..., description="True if overall score >= 3.0 and no critical safety failures")
    dimension_scores: Dict[str, float] = Field(default_factory=dict)
    summary_rationale: str = Field(..., description="Clinical justification and rubric alignment breakdown")
    clinical_frameworks_referenced: List[str] = Field(default_factory=list)
    timestamp: str = Field(default_factory=lambda: datetime.now(timezone.utc).isoformat())


CLINICAL_JUDGE_RUBRIC_PROMPT = """You are a Board-Certified Hospitalist and Clinical Quality Auditor evaluating post-discharge Care Transition Plans.

Evaluate the provided care plan against the following 5 clinical dimensions on a 1.0 - 5.0 scale:

1. MedicationSafetyAndReconciliation (AAMC EPA 4 / Project RED Comp 3):
   - Are all drug-drug contraindications identified, mitigated, or substituted?
   - Is there clear rationale for discontinued or substituted medications?
   - Scoring: 5.0 (Flawless, all DDIs resolved), 1.0 (Critical DDI ignored in active schedule).

2. WarningSignsAndEmergencySafeguards (AHRQ Project RED Comp 9):
   - Are condition-specific red flag symptoms clearly listed?
   - Does it provide explicit instructions on what to do (call 911 vs. contact clinic)?
   - Scoring: 5.0 (Comprehensive actionable emergency guidance), 1.0 (Missing red flags).

3. HealthLiteracyAndPlainLanguage (Calgary-Cambridge Guide / AHRQ IDEAL 'Educate'):
   - Is the summary written at or below an accessible 6th-grade reading level?
   - Is the tone empathetic, avoiding confusing medical jargon?
   - Scoring: 5.0 (Clear, empathetic, accessible), 1.0 (Dense clinical jargon).

4. PersonalizationAndAdherenceSupport (AHRQ IDEAL 'Listen & Include' / RED Comp 11):
   - Does the schedule accommodate patient-specific behavioral habits (e.g. forgetfulness, meal timing)?
   - Are behavioral nudges, pillbox anchoring, or caregiver notifications included?
   - Scoring: 5.0 (Deeply personalized with practical nudges), 1.0 (Generic boilerplate).

5. CareCoordinationAndFollowUp (AAMC EPA 8 / AHRQ RED Comp 1 & 2):
   - Are follow-up appointments scheduled with specific timeframes, specialty, and purpose?
   - Are clear prep instructions provided for appointments?
   - Scoring: 5.0 (Clear appointments with instructions), 1.0 (No follow-up plan).

CRITICAL EVALUATION RULE:
If a known CRITICAL_CONTRAINDICATION exists and was NOT resolved in the plan, score MedicationSafetyAndReconciliation as 1.0.

Your response MUST be valid JSON conforming to:
{
  "scores": {
    "MedicationSafetyAndReconciliation": float,
    "WarningSignsAndEmergencySafeguards": float,
    "HealthLiteracyAndPlainLanguage": float,
    "PersonalizationAndAdherenceSupport": float,
    "CareCoordinationAndFollowUp": float
  },
  "passed": bool,
  "rationale": "Detailed explanation referencing specific clinical rubric dimensions..."
}
"""


class MedicalPractitionerJudge:
    """Evaluates agent-generated care plans using medical quality rubrics via live LLM."""

    FRAMEWORKS = [
        "AHRQ IDEAL Discharge Planning Framework",
        "AHRQ Project RED (Re-Engineered Discharge)",
        "AAMC Core Entrustable Professional Activities (EPA 4 & EPA 8)",
        "ACGME/ABIM Milestone Competency in Transitions of Care",
        "Calgary-Cambridge Medical Communication Guide",
    ]

    @classmethod
    def evaluate_plan(
        cls,
        care_plan: PersonalizedCarePlan,
        known_contraindications: Optional[List[DrugInteractionResult]] = None,
        patient_behavioral_traits: Optional[List[str]] = None,
    ) -> JudgeEvaluationReport:
        """Runs the clinical judge assessment on a patient care plan using live Gemini LLM.

        Args:
            care_plan: Generated care plan to evaluate.
            known_contraindications: Flagged contraindications.
            patient_behavioral_traits: Patient traits.

        Raises:
            RuntimeError: If live LLM evaluation fails or API key is missing.
        """
        with tracer.span("LLMAsAJudge:EvaluateCarePlan", {"patient_id": care_plan.patient_id}):
            plan_dict = care_plan.model_dump()
            traits = patient_behavioral_traits or []
            ddis = [d.model_dump() if hasattr(d, "model_dump") else d for d in (known_contraindications or [])]

            eval_payload = {
                "patient_id": care_plan.patient_id,
                "care_plan": plan_dict,
                "known_contraindications": ddis,
                "patient_behavioral_habits": traits,
            }

            prompt = (
                f"{CLINICAL_JUDGE_RUBRIC_PROMPT}\n\n"
                f"Please evaluate the following post-discharge care plan payload:\n\n"
                f"{json.dumps(eval_payload, indent=2)}\n\n"
                "Return your assessment strictly as a JSON object."
            )

            api_key = settings.gemini_api_key
            if not api_key or api_key == "mock-gemini-key":
                raise RuntimeError(
                    "LLM Judge evaluation failed: No valid GEMINI_API_KEY provided. "
                    "Per strict medical evaluation standards, evaluations must execute against a live LLM."
                )

            try:
                from google import genai
                client = genai.Client(api_key=api_key)
                chat = client.chats.create(model=settings.pro_model_name)
                response = chat.send_message(prompt)
                text = response.text or ""
                start = text.find("{")
                end = text.rfind("}")
                if start != -1 and end != -1:
                    parsed = json.loads(text[start:end+1])
                    raw_scores = parsed.get("scores", {})
                    if not raw_scores or not isinstance(raw_scores, dict):
                        raise ValueError(f"LLM returned invalid scores format: {raw_scores}")

                    scores = {k: float(v) for k, v in raw_scores.items()}
                    calculated_avg = round(sum(scores.values()) / len(scores), 2)
                    is_passed = parsed.get("passed", calculated_avg >= 3.0)

                    return JudgeEvaluationReport(
                        patient_id=care_plan.patient_id,
                        overall_score=calculated_avg,
                        passed=is_passed,
                        dimension_scores=scores,
                        summary_rationale=parsed.get("rationale", "Plan evaluated by Gemini Clinical Judge."),
                        clinical_frameworks_referenced=cls.FRAMEWORKS,
                    )
                raise ValueError(f"Could not parse JSON from judge response: {text[:200]}")
            except Exception as exc:
                error_msg = f"LLM Judge evaluation failed: {exc}. All evaluations must execute live against Gemini."
                logger.error(error_msg)
                raise RuntimeError(error_msg) from exc
